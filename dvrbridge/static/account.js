(async () => {
  const $ = (id) => document.getElementById(id);
  const say = (id, text, ok) => { $(id).textContent = text || ''; $(id).className = ok ? 'ok' : 'err'; };
  const me = await loadNav('account');
  if (!me.username) return;
  $('who').textContent = 'Signed in as ' + me.username + ' (' + me.role + ', ' +
    (me.source === 'local' ? 'local account' : me.source === 'oidc' ? 'single sign-on' : 'reverse proxy') + ').';
  if (new URLSearchParams(location.search).get('enrol') && me.totp_required && !me.totp_enabled) $('enrolNotice').hidden = false;

  if (!me.can_change_password) { $('external').hidden = me.mode === 'none'; return; }
  $('pwSection').hidden = false;
  $('totpSection').hidden = false;

  const showTotp = () => {
    $('totpState').textContent = me.totp_enabled ? 'On. You are asked for a code each time you log in.'
                                                 : 'Off.' + (me.totp_required ? ' This server requires it.' : '');
    $('totpStart').hidden = me.totp_enabled;
    $('disableForm').hidden = !me.totp_enabled || me.totp_required;
  };
  showTotp();

  $('pwForm').addEventListener('submit', async (ev) => {
    ev.preventDefault();
    if ($('new1').value !== $('new2').value) { say('pwMsg', 'The new passwords do not match.'); return; }
    const r = await api('POST', '/api/account/password', { current: $('cur').value, new: $('new1').value });
    if (!r.ok) { say('pwMsg', r.data.detail || 'Could not change the password.'); return; }
    $('pwForm').reset();
    say('pwMsg', 'Password changed. Other devices were signed out.', true);
  });

  let pendingSecret = null;
  $('begin').addEventListener('click', async () => {
    const r = await api('POST', '/api/account/totp/begin');
    if (!r.ok) { say('totpMsg', r.data.detail || 'Could not start.'); return; }
    pendingSecret = r.data.secret;
    $('qr').innerHTML = r.data.qr_svg;            // SVG generated by the server; contains no user text
    $('secret').textContent = r.data.secret;
    $('enrol').hidden = false; $('totpStart').hidden = true;
    $('code').focus();
  });

  $('confirmForm').addEventListener('submit', async (ev) => {
    ev.preventDefault();
    const r = await api('POST', '/api/account/totp/confirm', { secret: pendingSecret, code: $('code').value });
    if (!r.ok) { say('totpMsg', r.data.detail || 'That code did not work.'); return; }
    me.totp_enabled = true;
    $('enrol').hidden = true; $('enrolNotice').hidden = true;
    showTotp();
    say('totpMsg', '');
    $('totpState').textContent = 'On. Other devices were signed out; you will be asked for a code at your next login.';
  });

  $('disableForm').addEventListener('submit', async (ev) => {
    ev.preventDefault();
    const r = await api('POST', '/api/account/totp/disable', { password: $('disablePw').value });
    if (!r.ok) { say('disableMsg', r.data.detail || 'Could not turn it off.'); return; }
    me.totp_enabled = false; $('disableForm').reset(); showTotp();
    say('disableMsg', 'Two-factor is off.', true);
  });
})();
